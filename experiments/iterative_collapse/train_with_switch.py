from pathlib import Path
# Add parent directory to path for imports
sys.path.insert(0, str(Path(__file__).parent.parent.parent))

import argparse
import time
import json
from datetime import datetime
import yaml

import torch
from torch import nn
from transformer import TransformerModel
from bar_distribution import BarDistribution, FullSupportBarDistribution, get_bucket_limits
from utils import (get_cosine_schedule_with_warmup, get_openai_lr, StoreDictKeyPair,
                   get_weighted_single_eval_pos_sampler, get_uniform_single_eval_pos_sampler)
import priors
from priors import pfn_synthetic
import encoders
import positional_encodings

from evaluate import evaluate_on_test_set


def train_with_switch(
    true_prior_class,
    criterion,
    encoder_generator,
    switch_epoch=100,
    total_epochs=200,
    synthetic_mode='sample',
    synthetic_ratio=1.0,
    use_autoregressive_synthetic=False,
    emsize=512,
    nhid=1024,
    nlayers=6,
    nhead=4,
    dropout=0.0,
    steps_per_epoch=100,
    batch_size=1000,
    bptt=10,
    lr=0.001,
    warmup_epochs=50,
    input_normalization=False,
    y_encoder_generator=None,
    pos_encoder_generator=None,
    decoder=None,
    extra_prior_kwargs_dict={},
    scheduler=get_cosine_schedule_with_warmup,
    load_weights_from_this_state_dict=None,
    validation_period=10,
    single_eval_pos_gen=None,
    gpu_device='cuda:0',
    aggregate_k_gradients=1,
    verbose=True,
    save_dir='./checkpoints',
    metrics_dir='./metrics',
    experiment_name='collapse_experiment'
):
    """
    Train a PFN model with data source switching.

    Args:
        true_prior_class: DataLoader class for true data (e.g., priors.fast_gp.DataLoader)
        criterion: Loss function
        encoder_generator: Function to create encoder
        switch_epoch: Epoch at which to switch to synthetic data
        total_epochs: Total number of training epochs
        synthetic_mode: 'mean' or 'sample' - how to generate synthetic Y
        synthetic_ratio: Ratio of synthetic data after switch (1.0 = pure synthetic)
        use_autoregressive_synthetic: Use slower but more accurate autoregressive generation
        ... (other training hyperparameters)
        save_dir: Directory to save model checkpoints
        metrics_dir: Directory to save training metrics
        experiment_name: Name for this experiment run
    """

    device = gpu_device if torch.cuda.is_available() else 'cpu:0'
    print(f'Using {device} device')
    print(f'Experiment: {experiment_name}')
    print(f'Will switch to synthetic data at epoch {switch_epoch}/{total_epochs}')
    print(f'Synthetic mode: {synthetic_mode}, ratio: {synthetic_ratio}')

    # Create directories
    Path(save_dir).mkdir(parents=True, exist_ok=True)
    Path(metrics_dir).mkdir(parents=True, exist_ok=True)

    # Create true data loader
    true_dl = true_prior_class(num_steps=steps_per_epoch, batch_size=batch_size,
                               seq_len=bptt, **extra_prior_kwargs_dict)

    # Create a fixed test set from true data for consistent evaluation
    print("Creating fixed test set from true GP data...")
    test_set_size = 100  # Number of test sequences
    test_batches = []
    test_dl = true_prior_class(num_steps=test_set_size, batch_size=10,
                               seq_len=bptt, **extra_prior_kwargs_dict)
    for data, targets in test_dl:
        test_batches.append((data, targets))
    print(f"Created {len(test_batches)} test batches")

    # Build model
    encoder = encoder_generator(true_dl.num_features + 1 if true_dl.fuse_x_y else true_dl.num_features, emsize)
    n_out = true_dl.num_outputs

    if isinstance(criterion, nn.GaussianNLLLoss):
        n_out *= 2
    elif isinstance(criterion, BarDistribution) or "BarDistribution" in criterion.__class__.__name__:
        assert n_out == 1
        n_out = criterion.num_bars

    model = TransformerModel(
        encoder, n_out, emsize, nhead, nhid, nlayers, dropout,
        y_encoder=y_encoder_generator(1, emsize) if y_encoder_generator else None,
        input_normalization=input_normalization,
        pos_encoder=(pos_encoder_generator or positional_encodings.NoPositionalEncoding)(emsize, bptt * 2),
        decoder=decoder
    )
    model.criterion = criterion

    if load_weights_from_this_state_dict is not None:
        model.load_state_dict(load_weights_from_this_state_dict)

    model.to(device)

    # Optimizer and scheduler
    if lr is None:
        lr = get_openai_lr(model)
        print(f"Using OpenAI max lr of {lr}.")
    optimizer = torch.optim.Adam(model.parameters(), lr=lr)
    scheduler_fn = scheduler(optimizer, warmup_epochs, total_epochs)

    # Loss function name for synthetic prior
    loss_function_name = 'gaussnll'  # Default
    if isinstance(criterion, nn.MSELoss):
        loss_function_name = 'mse'
    elif isinstance(criterion, nn.CrossEntropyLoss):
        loss_function_name = 'ce'
    elif isinstance(criterion, (BarDistribution, FullSupportBarDistribution)):
        loss_function_name = 'barnll'

    # Metrics tracking
    metrics = {
        'epochs': [],
        'train_loss': [],
        'test_loss_true': [],
        'data_source': [],
        'synthetic_ratio': [],
        'lr': [],
        'prediction_variance': [],
        'time_per_epoch': []
    }

    def train_epoch(dataloader, epoch_num, data_source_name):
        """Train for one epoch."""
        model.train()
        total_loss = 0.
        total_positional_losses = 0.
        total_positional_losses_recorded = 0
        start_time = time.time()

        for batch, (data, targets) in enumerate(dataloader):
            single_eval_pos = single_eval_pos_gen() if callable(single_eval_pos_gen) else single_eval_pos_gen
            output = model(
                tuple(e.to(device) for e in data) if isinstance(data, tuple) else data.to(device),
                single_eval_pos=single_eval_pos
            )

            if single_eval_pos is not None:
                targets = targets[single_eval_pos:]

            # Compute loss
            if isinstance(criterion, nn.GaussianNLLLoss):
                mean_pred = output[..., 0]
                var_pred = output[..., 1].abs()
                losses = criterion(mean_pred.flatten(), targets.to(device).flatten(), var=var_pred.flatten())
            elif isinstance(criterion, (nn.MSELoss, nn.BCEWithLogitsLoss)):
                losses = criterion(output.flatten(), targets.to(device).flatten())
            else:
                losses = criterion(output.reshape(-1, n_out), targets.to(device).flatten())

            losses = losses.view(*output.shape[0:2]).squeeze(-1)
            loss = losses.mean()

            # === DIAGNOSTIC LOGGING ===
            if torch.isnan(loss):
                import json
                from pathlib import Path
                debug_info = {'epoch': epoch_num, 'batch': batch, 'data_source': data_source_name}
                if isinstance(data, tuple):
                    debug_info['y_data_range'] = [data[1].min().item(), data[1].max().item()]
                    debug_info['y_has_nan'] = torch.isnan(data[1]).any().item()
                if isinstance(criterion, nn.GaussianNLLLoss):
                    var_raw = output[..., 1]
                    debug_info['var_raw_range'] = [var_raw.min().item(), var_raw.max().item()]
                    debug_info['var_has_negative'] = (var_raw < 0).any().item()
                    debug_info['var_num_negative'] = (var_raw < 0).sum().item()
                    debug_info['var_num_total'] = var_raw.numel()
                    debug_info['mean_pred_range'] = [mean_pred.min().item(), mean_pred.max().item()]
                    debug_info['targets_range'] = [targets.min().item(), targets.max().item()]
                Path(f'/tmp/nan_debug_epoch{epoch_num}_batch{batch}.json').write_text(json.dumps(debug_info, indent=2))
                print(f"\n!!! NaN LOSS at epoch {epoch_num}, batch {batch}! Debug: /tmp/nan_debug_epoch{epoch_num}_batch{batch}.json")
            # === END DIAGNOSTIC ===

            loss.backward()

            if batch % aggregate_k_gradients == aggregate_k_gradients - 1:
                torch.nn.utils.clip_grad_norm_(model.parameters(), 1.)
                optimizer.step()
                optimizer.zero_grad()

            total_loss += loss.item()
            total_positional_losses += losses.mean(1).cpu().detach() if single_eval_pos is None else \
                nn.functional.one_hot(torch.tensor(single_eval_pos), bptt) * loss.cpu().detach()
            total_positional_losses_recorded += torch.ones(bptt) if single_eval_pos is None else \
                nn.functional.one_hot(torch.tensor(single_eval_pos), bptt)

        epoch_time = time.time() - start_time
        avg_loss = total_loss / steps_per_epoch
        positional_losses = (total_positional_losses / total_positional_losses_recorded).tolist()

        return avg_loss, positional_losses, epoch_time

    # Main training loop
    print(f"\n{'='*80}")
    print(f"Starting training: {total_epochs} epochs, switch at epoch {switch_epoch}")
    print(f"{'='*80}\n")

    for epoch in range(1, total_epochs + 1):
        epoch_start_time = time.time()

        # Determine data source
        if epoch < switch_epoch:
            # Use true data
            dataloader = true_dl
            data_source = "true_gp"
            current_synthetic_ratio = 0.0
        else:
            # Switch to synthetic data
            # Create synthetic data loader using CURRENT model state
            synthetic_prior_kwargs = {
                **extra_prior_kwargs_dict,
                'model': model,
                'loss_function': loss_function_name,
                'sampling_mode': synthetic_mode,
                'num_features': true_dl.num_features,
            }

            if use_autoregressive_synthetic:
                synthetic_dl = pfn_synthetic.DataLoaderAutoregressive(
                    num_steps=steps_per_epoch,
                    batch_size=batch_size,
                    seq_len=bptt,
                    **synthetic_prior_kwargs
                )
            else:
                synthetic_dl = pfn_synthetic.DataLoader(
                    num_steps=steps_per_epoch,
                    batch_size=batch_size,
                    seq_len=bptt,
                    **synthetic_prior_kwargs
                )

            if synthetic_ratio >= 1.0:
                # Pure synthetic
                dataloader = synthetic_dl
                data_source = "synthetic"
                current_synthetic_ratio = 1.0
            else:
                # Mixed data - not implemented yet
                # For now, just use synthetic
                dataloader = synthetic_dl
                data_source = f"mixed_{synthetic_ratio}"
                current_synthetic_ratio = synthetic_ratio

        # Train for one epoch
        train_loss, positional_losses, epoch_time = train_epoch(
            dataloader, epoch, data_source
        )

        # Evaluate on true test set
        test_loss_true, test_variance = evaluate_on_test_set(
            model, test_batches, criterion, n_out, device
        )

        # Update learning rate
        scheduler_fn.step()
        current_lr = optimizer.param_groups[0]['lr']

        # Record metrics
        metrics['epochs'].append(epoch)
        metrics['train_loss'].append(train_loss)
        metrics['test_loss_true'].append(test_loss_true)
        metrics['data_source'].append(data_source)
        metrics['synthetic_ratio'].append(current_synthetic_ratio)
        metrics['lr'].append(current_lr)
        metrics['prediction_variance'].append(test_variance)
        metrics['time_per_epoch'].append(epoch_time)

        # Print progress
        if verbose:
            print(f'| epoch {epoch:3d}/{total_epochs} | time: {epoch_time:5.2f}s | '
                  f'source: {data_source:12s} | train loss {train_loss:5.3f} | '
                  f'test loss {test_loss_true:5.3f} | lr {current_lr:.6f}')

            if epoch == switch_epoch:
                print(f"\n{'!'*80}")
                print(f"!!! SWITCHING TO SYNTHETIC DATA AT EPOCH {epoch} !!!")
                print(f"{'!'*80}\n")

        # Save checkpoint periodically
        if epoch % validation_period == 0 or epoch == switch_epoch or epoch == total_epochs:
            checkpoint_path = Path(save_dir) / f'{experiment_name}_epoch_{epoch}.pt'
            torch.save({
                'epoch': epoch,
                'model_state_dict': model.state_dict(),
                'optimizer_state_dict': optimizer.state_dict(),
                'train_loss': train_loss,
                'test_loss_true': test_loss_true,
                'data_source': data_source,
            }, checkpoint_path)
            if verbose:
                print(f'    Checkpoint saved to {checkpoint_path}')

        # Save metrics after each epoch
        metrics_path = Path(metrics_dir) / f'{experiment_name}_metrics.json'
        with open(metrics_path, 'w') as f:
            json.dump(metrics, f, indent=2)

    print(f"\n{'='*80}")
    print(f"Training complete!")
    print(f"{'='*80}\n")
    print(f"Final train loss: {metrics['train_loss'][-1]:.4f}")
    print(f"Final test loss (true GP): {metrics['test_loss_true'][-1]:.4f}")
    print(f"Metrics saved to: {metrics_path}")

    return model, metrics


if __name__ == '__main__':
    config_parser = argparse.ArgumentParser(description='Config file parser')
    config_parser.add_argument('--config', type=str, default=None,
                              help='Path to config YAML file')

    parser = argparse.ArgumentParser(description='Train PFN with data source switch')

    # Experiment parameters
    parser.add_argument('--experiment_name', type=str, default=None,
                       help='Name for this experiment (default: auto-generated)')
    parser.add_argument('--experiment_prefix', type=str, default='',
                       help='Prefix to add to auto-generated experiment name')
    parser.add_argument('--switch_epoch', type=int, default=100,
                       help='Epoch at which to switch to synthetic data')
    parser.add_argument('--total_epochs', type=int, default=200,
                       help='Total number of epochs to train')
    parser.add_argument('--synthetic_mode', type=str, default='sample',
                       choices=['mean', 'sample'],
                       help='How to generate synthetic Y values')
    parser.add_argument('--synthetic_ratio', type=float, default=1.0,
                       help='Ratio of synthetic data after switch (1.0 = pure synthetic)')
    parser.add_argument('--use_autoregressive_synthetic', action='store_true',
                       help='Use slower autoregressive synthetic data generation')

    # Data parameters
    parser.add_argument('--prior', type=str, default='gp',
                       help='Which prior/data source to use (gp, ridge, stroke, or mix_gp if available)')
    parser.add_argument('--num_features', default=1, type=int,
                       help='Number of input features for the prior')
    parser.add_argument('--loss_function', default='gaussnll',
                       choices=['gaussnll', 'mse', 'ce', 'barnll'],
                       help='Loss function')
    parser.add_argument('--bptt', default=10, type=int, help='Sequence length')
    parser.add_argument('--batch_size', default=1000, type=int)
    parser.add_argument('--steps_per_epoch', default=100, type=int)

    # Model parameters
    parser.add_argument('--emsize', default=512, type=int, help='Embedding dimension')
    parser.add_argument('--nlayers', default=6, type=int, help='Number of transformer layers')
    parser.add_argument('--nhid', default=None, type=int, help='Hidden dimension (default: 2*emsize)')
    parser.add_argument('--nhead', default=4, type=int, help='Number of attention heads')
    parser.add_argument('--dropout', default=0.0, type=float)

    # Training parameters
    parser.add_argument('--lr', default=0.001, type=float, help='Learning rate')
    parser.add_argument('--warmup_epochs', default=50, type=int)
    parser.add_argument('--validation_period', default=10, type=int)
    parser.add_argument('--permutation_invariant_max_eval_pos', default=None, type=int,
                       help='Max eval position for permutation invariant sampling (None uses all positions)')
    parser.add_argument('--permutation_invariant_sampling', default='weighted',
                       choices=['weighted', 'uniform'],
                       help='Sampling strategy for single_eval_pos')

    # Encoder parameters
    parser.add_argument('--encoder', default='linear', type=str,
                       help='Input encoder (linear is always available, mlp/positional may require additional code)')
    parser.add_argument('--y_encoder', default='linear', type=str,
                       help='Y encoder (linear is always available, mlp/positional may require additional code)')
    parser.add_argument('--pos_encoder', default='sinus', type=str,
                       choices=['sinus', 'learned', 'none'],
                       help='Positional encoding type')

    # Extra prior kwargs
    parser.add_argument("--extra_prior_kwargs_dict", default={'fuse_x_y': False},
                       dest="extra_prior_kwargs_dict", action=StoreDictKeyPair,
                       nargs="+", metavar="KEY=VAL")

    # Paths
    parser.add_argument('--save_dir', type=str,
                       default='./experiments/iterative_collapse/checkpoints')
    parser.add_argument('--metrics_dir', type=str,
                       default='./experiments/iterative_collapse/metrics')
    parser.add_argument('--generate_plots', action='store_true',
                       help='Automatically generate plots after training')

    # Parse arguments
    args_config, remaining = config_parser.parse_known_args()
    if args_config.config:
        with open(args_config.config, 'r') as f:
            cfg = yaml.safe_load(f)

            # Process hyperparameters if using underfit_learning configs
            # This converts string specifications like "uniform_int(3, 8)" to callables
            if 'extra_prior_kwargs_dict' in cfg and 'hyperparameters' in cfg['extra_prior_kwargs_dict']:
                try:
                    # Try to import config_utils for advanced hyperparameter processing
                    from pathlib import Path
                    underfit_path = Path(__file__).parent.parent / 'underfit_learning'
                    if underfit_path.exists():
                        sys.path.insert(0, str(underfit_path))
                        from config_utils import process_hyperparameters
                        cfg['extra_prior_kwargs_dict']['hyperparameters'] = process_hyperparameters(
                            cfg['extra_prior_kwargs_dict']['hyperparameters']
                        )
                        print("✓ Processed hyperparameters using config_utils")
                except ImportError:
                    # If config_utils not available, hyperparameters should already be callables
                    print("Note: config_utils not found, assuming hyperparameters are already callables")
                    pass

            parser.set_defaults(**cfg)

    args = parser.parse_args(remaining)

    # Generate experiment name if not provided
    if args.experiment_name is None:
        timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
        auto_str = 'auto' if args.use_autoregressive_synthetic else 'noauto'
        prefix = f'{args.experiment_prefix}_' if args.experiment_prefix else ''
        args.experiment_name = (
            f'{prefix}{args.prior}_d{args.num_features}_seq{args.bptt}_'
            f'sw{args.switch_epoch}of{args.total_epochs}_{auto_str}_'
            f'{args.synthetic_mode}_r{args.synthetic_ratio}_{timestamp}'
        )

    # Set nhid if not specified
    if args.nhid is None:
        args.nhid = 2 * args.emsize

    # Ensure num_features is in extra_prior_kwargs_dict
    if 'num_features' not in args.extra_prior_kwargs_dict:
        args.extra_prior_kwargs_dict['num_features'] = args.num_features

    # Select prior (only include available priors)
    prior_map = {
        'gp': priors.fast_gp.DataLoader,
        'ridge': priors.ridge.DataLoader,
        'stroke': priors.stroke.DataLoader,
    }

    # Add optional priors if available
    if hasattr(priors, 'fast_gp_mix'):
        prior_map['mix_gp'] = priors.fast_gp_mix.DataLoader
    if hasattr(priors, 'mlp'):
        prior_map['mlp'] = priors.mlp.DataLoader

    if args.prior not in prior_map:
        available = ', '.join(prior_map.keys())
        raise ValueError(f"Prior '{args.prior}' not available. Available priors: {available}")

    prior_class = prior_map[args.prior]

    # Select loss function
    loss_map = {
        'gaussnll': nn.GaussianNLLLoss(reduction='none', full=True),
        'mse': nn.MSELoss(reduction='none'),
        'ce': nn.CrossEntropyLoss(reduction='none'),
    }
    criterion = loss_map[args.loss_function]

    # Select encoders (only include available encoders)
    encoder_map = {
        'linear': encoders.Linear,
    }

    # Add optional encoders if available
    if hasattr(encoders, 'MLP'):
        encoder_map['mlp'] = encoders.MLP
    if hasattr(encoders, 'Positional'):
        encoder_map['positional'] = encoders.Positional

    if args.encoder not in encoder_map:
        available = ', '.join(encoder_map.keys())
        raise ValueError(f"Encoder '{args.encoder}' not available. Available encoders: {available}")
    if args.y_encoder not in encoder_map:
        available = ', '.join(encoder_map.keys())
        raise ValueError(f"Y-encoder '{args.y_encoder}' not available. Available encoders: {available}")

    encoder_gen = encoder_map[args.encoder]
    y_encoder_gen = encoder_map[args.y_encoder]

    # Select positional encoder
    pos_encoder_map = {
        'sinus': positional_encodings.PositionalEncoding,
        'learned': positional_encodings.LearnedPositionalEncoding,
        'none': positional_encodings.NoPositionalEncoding,
    }
    pos_encoder_gen = pos_encoder_map[args.pos_encoder]

    # Set up single_eval_pos_gen
    # If permutation_invariant_max_eval_pos is None, use bptt as default
    max_eval_pos = args.permutation_invariant_max_eval_pos if args.permutation_invariant_max_eval_pos is not None else args.bptt

    if args.permutation_invariant_sampling == 'weighted':
        single_eval_pos_gen = get_weighted_single_eval_pos_sampler(max_eval_pos)
    elif args.permutation_invariant_sampling == 'uniform':
        single_eval_pos_gen = get_uniform_single_eval_pos_sampler(max_eval_pos)
    else:
        # Default to weighted sampling
        single_eval_pos_gen = get_weighted_single_eval_pos_sampler(max_eval_pos)

    # Print configuration
    print("\n" + "="*80)
    print("EXPERIMENT CONFIGURATION")
    print("="*80)
    for key, value in vars(args).items():
        print(f"  {key:30s}: {value}")
    print("="*80 + "\n")

    # Run training
    model, metrics = train_with_switch(
        true_prior_class=prior_class,
        criterion=criterion,
        encoder_generator=encoder_gen,
        switch_epoch=args.switch_epoch,
        total_epochs=args.total_epochs,
        synthetic_mode=args.synthetic_mode,
        synthetic_ratio=args.synthetic_ratio,
        use_autoregressive_synthetic=args.use_autoregressive_synthetic,
        emsize=args.emsize,
        nhid=args.nhid,
        nlayers=args.nlayers,
        nhead=args.nhead,
        dropout=args.dropout,
        steps_per_epoch=args.steps_per_epoch,
        batch_size=args.batch_size,
        bptt=args.bptt,
        lr=args.lr,
        warmup_epochs=args.warmup_epochs,
        y_encoder_generator=y_encoder_gen,
        pos_encoder_generator=pos_encoder_gen,
        extra_prior_kwargs_dict=args.extra_prior_kwargs_dict,
        validation_period=args.validation_period,
        single_eval_pos_gen=single_eval_pos_gen,
        save_dir=args.save_dir,
        metrics_dir=args.metrics_dir,
        experiment_name=args.experiment_name,
    )

    # Generate plots if requested
    if args.generate_plots:
        print("\nGenerating plots...")
        try:
            import matplotlib
            matplotlib.use('Agg')  # Non-interactive backend for server
            import matplotlib.pyplot as plt
            from pathlib import Path

            # Create plots directory
            plots_dir = Path('./experiments/iterative_collapse/plots')
            plots_dir.mkdir(parents=True, exist_ok=True)

            # Load metrics from saved file
            metrics_file = Path(args.metrics_dir) / f'{args.experiment_name}_metrics.json'
            import json
            with open(metrics_file, 'r') as f:
                metrics_data = json.load(f)

            # Create figure with 2x2 subplots
            fig, axes = plt.subplots(2, 2, figsize=(14, 10))
            fig.suptitle(f'Model Collapse Analysis: {args.experiment_name}', fontsize=14, fontweight='bold')

            epochs = metrics_data['epochs']
            train_loss = metrics_data['train_loss']
            test_loss = metrics_data['test_loss_true']
            variance = metrics_data['prediction_variance']
            lr_vals = metrics_data['lr']

            # Plot 1: Train vs Test Loss
            ax1 = axes[0, 0]
            pre_switch = [i for i, e in enumerate(epochs) if e < args.switch_epoch]
            post_switch = [i for i, e in enumerate(epochs) if e >= args.switch_epoch]

            if pre_switch:
                ax1.plot([epochs[i] for i in pre_switch], [train_loss[i] for i in pre_switch],
                        'b-', alpha=0.7, linewidth=1.5, label='Train (True Data)')
                ax1.plot([epochs[i] for i in pre_switch], [test_loss[i] for i in pre_switch],
                        'g-', alpha=0.7, linewidth=1.5, label='Test (True Data)')
            if post_switch:
                ax1.plot([epochs[i] for i in post_switch], [train_loss[i] for i in post_switch],
                        'b--', alpha=0.7, linewidth=1.5, label='Train (Synthetic)')
                ax1.plot([epochs[i] for i in post_switch], [test_loss[i] for i in post_switch],
                        'r-', alpha=0.7, linewidth=1.5, label='Test (Synthetic)')

            ax1.axvline(args.switch_epoch, color='black', linestyle='--', linewidth=2, alpha=0.5, label='Switch')
            ax1.set_xlabel('Epoch')
            ax1.set_ylabel('Loss')
            ax1.set_title('Train vs Test Loss')
            ax1.legend(fontsize=8)
            ax1.grid(True, alpha=0.3)
            ax1.set_yscale('log')

            # Plot 2: Variance Trajectory
            ax2 = axes[0, 1]
            if pre_switch:
                ax2.plot([epochs[i] for i in pre_switch], [variance[i] for i in pre_switch],
                        'g-', linewidth=2, label='True Data')
            if post_switch:
                ax2.plot([epochs[i] for i in post_switch], [variance[i] for i in post_switch],
                        'r-', linewidth=2, label='Synthetic Data')
            ax2.axvline(args.switch_epoch, color='black', linestyle='--', linewidth=2, alpha=0.5)
            ax2.set_xlabel('Epoch')
            ax2.set_ylabel('Prediction Variance')
            ax2.set_title('Variance Trajectory (Mode Collapse Indicator)')
            ax2.legend()
            ax2.grid(True, alpha=0.3)
            ax2.set_yscale('log')

            # Plot 3: Learning Rate Schedule
            ax3 = axes[1, 0]
            ax3.plot(epochs, lr_vals, 'purple', linewidth=2)
            ax3.axvline(args.switch_epoch, color='black', linestyle='--', linewidth=2, alpha=0.5)
            ax3.set_xlabel('Epoch')
            ax3.set_ylabel('Learning Rate')
            ax3.set_title('Learning Rate Schedule')
            ax3.grid(True, alpha=0.3)

            # Plot 4: Summary Statistics
            ax4 = axes[1, 1]
            ax4.axis('off')

            pre_baseline = test_loss[args.switch_epoch - 1] if args.switch_epoch > 0 else test_loss[0]
            post_final = test_loss[-1]
            var_baseline = variance[args.switch_epoch - 1] if args.switch_epoch > 0 else variance[0]
            var_final = variance[-1]

            summary_text = f"""
EXPERIMENT SUMMARY

Configuration:
  Prior: {args.prior}
  Dimensions: {args.num_features}
  Sequence Length: {args.bptt}
  Switch Epoch: {args.switch_epoch}/{args.total_epochs}
  Autoregressive: {args.use_autoregressive_synthetic}
  Synthetic Ratio: {args.synthetic_ratio}

Pre-Switch (Epoch {args.switch_epoch}):
  Test Loss: {pre_baseline:.4f}
  Variance: {var_baseline:.4f}

Post-Switch (Epoch {args.total_epochs}):
  Test Loss: {post_final:.4f}
  Variance: {var_final:.4f}

Degradation:
  Test Loss: {post_final/pre_baseline:.2f}x worse
  Variance: {var_final/var_baseline:.2f}x change

Max Test Loss: {max(test_loss):.2f}
Min Train Loss: {min(train_loss):.4f}
"""
            ax4.text(0.05, 0.95, summary_text, transform=ax4.transAxes, fontsize=9,
                    verticalalignment='top', fontfamily='monospace',
                    bbox=dict(boxstyle='round', facecolor='wheat', alpha=0.3))

            plt.tight_layout()

            # Save plot
            plot_path = plots_dir / f'{args.experiment_name}.png'
            plt.savefig(plot_path, dpi=150, bbox_inches='tight')
            plt.close()

            print(f"✓ Plot saved to: {plot_path}")

        except Exception as e:
            print(f"✗ Failed to generate plots: {e}")
            import traceback
            traceback.print_exc()

