"""
Training Script with Data Source Switch

This script trains a PFN model initially on true GP data, then switches to
training on synthetic data generated by the model itself. This is designed
to study model collapse.

Usage:
    python train_with_switch.py --switch_epoch 100 --total_epochs 200
"""

